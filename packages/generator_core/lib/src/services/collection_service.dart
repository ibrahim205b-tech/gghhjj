class PaymentMethod {
  static const cash = 'cash';
  static const transfer = 'transfer';
  static const labels = {cash: 'نقداً', transfer: 'تحويل'};
}

/// Payments, receipts, collectors and their custody balances.
class CollectionService {
  final CoreContext ctx;
  final Store store;
  final AuditService audit;
  final LedgerService ledger;
  final SubscriberService subscribers;
  final NetworkService network;
  CollectionService(this.ctx, this.store, this.audit, this.ledger, this.subscribers, this.network);

  Future<String> _nextReceiptNo(DatabaseExecutor t) async {
    final key = 'receipt_seq';
    final r = await t.query('local_meta', where: 'key = ?', whereArgs: [key]);
    final n = r.isEmpty ? 1 : int.parse(r.first['value'] as String) + 1;
    await t.insert('local_meta', {'key': key, 'value': '$n'}, conflictAlgorithm: ConflictAlgorithm.replace);
    final dev = ctx.deviceId.replaceAll('-', '').toUpperCase();
    final prefix = dev.length >= 4 ? dev.substring(0, 4) : dev.padRight(4, '0');
    return '$prefix-${n.toString().padLeft(6, '0')}';
  }

  /// Records a payment. [requestId] is an idempotency key generated by the UI
  /// when the payment screen opens; pressing "save" twice (or a retry after a
  /// crash) returns the same payment instead of creating a duplicate.
  Future<Map<String, Object?>> recordPayment({
    required String subscriberId,
    required int amount,
    String? requestId,
    String? collectorId,
    String? cashboxId,
    String method = PaymentMethod.cash,
    String? notes,
  }) async {
    ctx.require(Perm.paymentsCollect);
    if (amount <= 0) throw validation('المبلغ يجب أن يكون أكبر من صفر.');
    final id = requestId ?? newId();
    final existing = await ctx.db.query('payments', where: 'id = ?', whereArgs: [id]);
    if (existing.isNotEmpty) return existing.first;

    final sub = await subscribers.get(subscriberId);
    final gen = sub['generator_id'] as String;
    if (sub['status'] == SubscriberStatus.transferred) {
      throw validation('المشترك منقول إلى مولدة أخرى؛ سجّل الدفعة على سجله الجديد أو كتسديد دين قديم من المالك.');
    }
    final s = ctx.session!;
    String? col = collectorId;
    if (s.isCollector) {
      if (s.collectorId == null) throw const PermissionDenied('collector.unlinked');
      col = s.collectorId; // a collector can only collect into his own custody
      await subscribers.requireCollectorScope(subscriberId);
    }
    String? box;
    if (col == null) {
      box = cashboxId ?? NetworkService.mainCashbox(gen);
    }
    late Map<String, Object?> row;
    await ctx.db.transaction((t) async {
      final receipt = await _nextReceiptNo(t);
      row = {
        'id': id,
        'generator_id': gen,
        'subscriber_id': subscriberId,
        'amount': amount,
        'method': method,
        'collector_id': col,
        'cashbox_id': box,
        'receipt_no': receipt,
        'paid_at': ctx.nowIso,
        'pay_date': ctx.today,
        'notes': notes,
        'created_by': ctx.userId,
        'device_id': ctx.deviceId,
        'reversal_of': null,
      };
      await store.insert(t, 'payments', row);
      final debitCode = col != null ? Acc.collectorCustody : await network.cashboxCode(box!, t);
      await ledger.post(t,
          entryId: 'je:pay:$id',
          generatorId: gen,
          date: ctx.today,
          description: 'تسديد اشتراك — ${sub['full_name']} (وصل $receipt)',
          sourceType: 'payment',
          sourceId: id,
          lines: [
            JLine.dr(debitCode, amount,
                partyType: col != null ? PartyType.collector : null, partyId: col),
            JLine.cr(Acc.receivables, amount, partyType: PartyType.subscriber, partyId: subscriberId),
          ]);
      await audit.log(t, 'payments.create', entity: 'payments', entityId: id, generatorId: gen,
          details: {'amount': amount, 'receipt': receipt, 'collector': col});
    });
    return row;
  }

  /// Payments cannot be deleted. A wrong payment is cancelled by a reversing
  /// payment record plus a reversing journal entry.
  Future<void> reversePayment(String paymentId, {required String reason}) async {
    ctx.require(Perm.paymentsReverse);
    if (reason.trim().length < 3) throw validation('يجب ذكر سبب الإلغاء.');
    final p = await ctx.db.query('payments', where: 'id = ?', whereArgs: [paymentId]);
    if (p.isEmpty) throw const DomainException('NOT_FOUND', 'الدفعة غير موجودة.');
    final pay = p.first;
    if (pay['reversal_of'] != null) throw validation('لا يمكن إلغاء قيد إلغاء.');
    ctx.requireGenerator(pay['generator_id'] as String);
    final rev = await ctx.db.query('payments', where: 'reversal_of = ?', whereArgs: [paymentId]);
    if (rev.isNotEmpty) throw const DomainException('ALREADY_REVERSED', 'تم إلغاء هذه الدفعة مسبقاً.');
    await ctx.db.transaction((t) async {
      await store.insert(t, 'payments', {
        'id': 'payrev:$paymentId',
        'generator_id': pay['generator_id'],
        'subscriber_id': pay['subscriber_id'],
        'amount': pay['amount'],
        'method': pay['method'],
        'collector_id': pay['collector_id'],
        'cashbox_id': pay['cashbox_id'],
        'receipt_no': '${pay['receipt_no']}-R',
        'paid_at': ctx.nowIso,
        'pay_date': ctx.today,
        'notes': 'إلغاء: $reason',
        'created_by': ctx.userId,
        'device_id': ctx.deviceId,
        'reversal_of': paymentId,
      });
      await ledger.reverse(t, 'je:pay:$paymentId', reason: reason);
      await audit.log(t, 'payments.reverse', entity: 'payments', entityId: paymentId,
          generatorId: pay['generator_id'] as String, details: {'reason': reason});
    });
  }

  Future<List<Map<String, Object?>>> subscriberPayments(String subscriberId) async {
    await subscribers.get(subscriberId);
    return ctx.db.rawQuery('''SELECT p.*, c.full_name AS collector_name,
        (SELECT 1 FROM payments r WHERE r.reversal_of = p.id) AS reversed
        FROM payments p LEFT JOIN collectors c ON c.id = p.collector_id
        WHERE p.subscriber_id = ? ORDER BY p.paid_at DESC''', [subscriberId]);
  }

  Future<List<Map<String, Object?>>> recentPayments(String generatorId, {int limit = 20, String? collectorId}) {
    ctx.requireGenerator(generatorId);
    final s = ctx.session;
    final col = s != null && s.isCollector ? s.collectorId ?? '-' : collectorId;
    return ctx.db.rawQuery('''SELECT p.*, s.full_name, s.account_no, c.full_name AS collector_name,
        (SELECT 1 FROM payments r WHERE r.reversal_of = p.id) AS reversed
        FROM payments p JOIN subscribers s ON s.id = p.subscriber_id
        LEFT JOIN collectors c ON c.id = p.collector_id
        WHERE p.generator_id = ? ${col != null ? 'AND p.collector_id = ?' : ''}
        ORDER BY p.paid_at DESC LIMIT ?''', [generatorId, if (col != null) col, limit]);
  }

  /// Data needed to render/print a receipt.
  Future<Map<String, Object?>> receipt(String paymentId) async {
    final r = await ctx.db.rawQuery('''SELECT p.*, s.full_name, s.account_no, s.amps, s.phone,
        g.name AS generator_name, c.full_name AS collector_name
        FROM payments p JOIN subscribers s ON s.id = p.subscriber_id JOIN generators g ON g.id = p.generator_id
        LEFT JOIN collectors c ON c.id = p.collector_id WHERE p.id = ?''', [paymentId]);
    if (r.isEmpty) throw const DomainException('NOT_FOUND', 'الوصل غير موجود.');
    final row = Map<String, Object?>.from(r.first);
    ctx.requireGenerator(row['generator_id'] as String);
    row['balance_after'] = await ledger.balance(row['generator_id'] as String, Acc.receivables,
        partyType: PartyType.subscriber, partyId: row['subscriber_id'] as String);
    return row;
  }

  // ------------------------------------------------------------ collectors

  Future<String> createCollector({
    required String fullName,
    String? phone,
    String? userId,
    int commissionPercent = 0,
    int monthlySalary = 0,
  }) async {
    ctx.require(Perm.collectorsManage);
    if (fullName.trim().length < 3) throw validation('اسم الجابي مطلوب.');
    if (commissionPercent < 0 || commissionPercent > 100) throw validation('نسبة العمولة بين 0 و 100.');
    final id = newId();
    await ctx.db.transaction((t) async {
      await store.insert(t, 'collectors', {
        'id': id, 'user_id': userId, 'full_name': fullName.trim(), 'phone': phone,
        'commission_percent': commissionPercent, 'monthly_salary': monthlySalary,
      });
      await audit.log(t, 'collectors.create', entity: 'collectors', entityId: id);
    });
    return id;
  }

  Future<void> updateCollector(String id, Map<String, Object?> changes) async {
    ctx.require(Perm.collectorsManage);
    const allowed = {'full_name', 'phone', 'user_id', 'commission_percent', 'monthly_salary', 'active', 'photo'};
    final c = Map.of(changes)..removeWhere((k, _) => !allowed.contains(k));
    await ctx.db.transaction((t) async {
      await store.update(t, 'collectors', id, c);
      await audit.log(t, 'collectors.update', entity: 'collectors', entityId: id, details: c);
    });
  }

  Future<List<Map<String, Object?>>> listCollectors() async {
    final s = ctx.session;
    if (s != null && s.isCollector) {
      return ctx.db.query('collectors', where: 'id = ?', whereArgs: [s.collectorId ?? '-']);
    }
    if (!ctx.can(Perm.collectorsViewAll) && !ctx.can(Perm.collectorsManage)) {
      throw const PermissionDenied(Perm.collectorsViewAll);
    }
    return ctx.db.query('collectors', where: 'active = 1', orderBy: 'full_name');
  }

  Future<String> assign(String collectorId, String generatorId, {String? areaId, String? cabinetId}) async {
    ctx.require(Perm.collectorsManage);
    ctx.requireGenerator(generatorId);
    final id = newId();
    await ctx.db.transaction((t) async {
      await store.insert(t, 'collector_assignments', {
        'id': id, 'collector_id': collectorId, 'generator_id': generatorId,
        'area_id': areaId, 'cabinet_id': cabinetId,
      });
      await audit.log(t, 'collectors.assign', entity: 'collectors', entityId: collectorId, generatorId: generatorId,
          details: {'area': areaId, 'cabinet': cabinetId});
    });
    return id;
  }

  Future<void> unassign(String assignmentId) async {
    ctx.require(Perm.collectorsManage);
    await ctx.db.transaction((t) async {
      await store.update(t, 'collector_assignments', assignmentId, {'active': 0});
      await audit.log(t, 'collectors.unassign', entity: 'collector_assignments', entityId: assignmentId);
    });
  }

  Future<List<Map<String, Object?>>> assignments(String collectorId) => ctx.db.rawQuery('''
      SELECT ca.*, a.name AS area_name, c.code AS cabinet_code, g.name AS generator_name
      FROM collector_assignments ca JOIN generators g ON g.id = ca.generator_id
      LEFT JOIN areas a ON a.id = ca.area_id LEFT JOIN cabinets c ON c.id = ca.cabinet_id
      WHERE ca.collector_id = ? AND ca.active = 1''', [collectorId]);

  void _requireCollectorVisible(String collectorId) {
    final s = ctx.session;
    if (s == null) throw const DomainException('NOT_AUTHENTICATED', 'يجب تسجيل الدخول أولاً.');
    if (s.isCollector && s.collectorId == collectorId) return;
    if (!ctx.can(Perm.collectorsViewAll)) throw const PermissionDenied(Perm.collectorsViewAll);
  }

  /// Money in a collector's custody (collected but not yet handed to a cash box).
  Future<int> custodyBalance(String generatorId, String collectorId) {
    _requireCollectorVisible(collectorId);
    return ledger.balance(generatorId, Acc.collectorCustody, partyType: PartyType.collector, partyId: collectorId);
  }

  /// Collector hands collected money to a cash box.
  Future<String> handover({
    required String generatorId,
    required String collectorId,
    required int amount,
    String? cashboxId,
    String? notes,
  }) async {
    ctx.require(Perm.cashboxManage);
    ctx.requireGenerator(generatorId);
    if (amount <= 0) throw validation('المبلغ يجب أن يكون أكبر من صفر.');
    final custody = await custodyBalance(generatorId, collectorId);
    if (amount > custody) {
      throw validation('المبلغ أكبر من الرصيد الموجود بعهدة الجابي (${custody.toString()}).');
    }
    final box = cashboxId ?? NetworkService.mainCashbox(generatorId);
    final id = newId();
    await ctx.db.transaction((t) async {
      await store.insert(t, 'collector_handovers', {
        'id': id, 'generator_id': generatorId, 'collector_id': collectorId, 'cashbox_id': box,
        'amount': amount, 'handover_date': ctx.today, 'notes': notes, 'created_at': ctx.nowIso,
        'created_by': ctx.userId,
      });
      final col = await t.query('collectors', where: 'id = ?', whereArgs: [collectorId]);
      await ledger.post(t,
          entryId: 'je:ho:$id',
          generatorId: generatorId,
          date: ctx.today,
          description: 'استلام مبالغ من الجابي ${col.isEmpty ? '' : col.first['full_name']}',
          sourceType: 'handover',
          sourceId: id,
          lines: [
            JLine.dr(await network.cashboxCode(box, t), amount),
            JLine.cr(Acc.collectorCustody, amount, partyType: PartyType.collector, partyId: collectorId),
          ]);
      await audit.log(t, 'collectors.handover', entity: 'collector_handovers', entityId: id,
          generatorId: generatorId, details: {'amount': amount, 'collector': collectorId});
    });
    return id;
  }

  /// Per-collector performance for a date range.
  Future<List<Map<String, Object?>>> collectorPerformance(String generatorId, DateRange range) async {
    ctx.requireGenerator(generatorId);
    final s = ctx.session;
    final onlyMe = s != null && s.isCollector;
    if (!onlyMe && !ctx.can(Perm.collectorsViewAll)) throw const PermissionDenied(Perm.collectorsViewAll);
    final custodyAcc = LedgerService.accountId(generatorId, Acc.collectorCustody);
    final rows = await ctx.db.rawQuery('''
      SELECT c.id, c.full_name, c.commission_percent, c.monthly_salary,
        COALESCE((SELECT SUM(CASE WHEN p.reversal_of IS NULL THEN p.amount ELSE -p.amount END) FROM payments p
          WHERE p.collector_id = c.id AND p.generator_id = ? AND p.pay_date BETWEEN ? AND ?), 0) AS collected,
        COALESCE((SELECT COUNT(*) FROM payments p WHERE p.collector_id = c.id AND p.generator_id = ?
          AND p.reversal_of IS NULL AND p.pay_date BETWEEN ? AND ?), 0) AS receipts,
        COALESCE((SELECT SUM(h.amount) FROM collector_handovers h WHERE h.collector_id = c.id
          AND h.generator_id = ? AND h.handover_date BETWEEN ? AND ?), 0) AS handed_over,
        COALESCE((SELECT SUM(debit - credit) FROM journal_lines jl WHERE jl.account_id = ?
          AND jl.party_type = 'collector' AND jl.party_id = c.id), 0) AS custody,
        (SELECT MAX(h.handover_date) FROM collector_handovers h WHERE h.collector_id = c.id
          AND h.generator_id = ?) AS last_handover
      FROM collectors c WHERE c.active = 1 ${onlyMe ? 'AND c.id = ?' : ''} ORDER BY collected DESC''', [
      generatorId, range.from, range.to,
      generatorId, range.from, range.to,
      generatorId, range.from, range.to,
      custodyAcc, generatorId,
      if (onlyMe) s.collectorId ?? '-',
    ]);
    return rows
        .map((r) => {
              ...r,
              'commission': ((r['collected'] as int) * (r['commission_percent'] as int) / 100).round(),
            })
        .toList();
  }
}
